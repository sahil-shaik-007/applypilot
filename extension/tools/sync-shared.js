#!/usr/bin/env node
// Generates extension/content/shared.js from the desktop app's form logic so the extension and the
// desktop auto-apply engine always use the same field scanner and the same answerer:
//   electron/apply/answers.js  -> globalThis.__apAnswers  (answerFromProfile, bestOption, ...)
//   electron/apply/dom.js      -> globalThis.__apScan, globalThis.__apReadListOptions (in-page functions)
//
//   node extension/tools/sync-shared.js          write the file
//   node extension/tools/sync-shared.js --check  exit 1 if the committed file is stale
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(__dirname, '..', 'content', 'shared.js');

function between(src, startMarker, endMarker) {
  const a = src.indexOf(startMarker);
  const b = src.indexOf(endMarker, a + 1);
  if (a < 0 || b < 0) throw new Error(`Marker not found: ${startMarker} / ${endMarker}`);
  return src.slice(a, b).trimEnd();
}

function build() {
  const answers = fs.readFileSync(path.join(ROOT, 'electron', 'apply', 'answers.js'), 'utf8').replace(/\r\n/g, '\n');
  const dom = fs.readFileSync(path.join(ROOT, 'electron', 'apply', 'dom.js'), 'utf8').replace(/\r\n/g, '\n');
  if (/\brequire\(/.test(answers)) throw new Error('answers.js now has require() calls — it can no longer be bundled verbatim');
  const scan = between(dom, 'function __apScan(cfg) {', '\nfunction __apReadListOptions(');
  const readList = between(dom, 'function __apReadListOptions(input) {', '\n/* eslint-enable no-undef */');
  return `// GENERATED by extension/tools/sync-shared.js from electron/apply/answers.js and electron/apply/dom.js.
// Do not edit by hand: change the desktop files and re-run \`node extension/tools/sync-shared.js\`.
/* eslint-disable */
(function () {
  if (globalThis.__apAnswers && globalThis.__apScan) return; // already injected into this frame
  const module = { exports: {} };
  // ---------------------------------------------------------------- electron/apply/answers.js
  (function (module) {
${answers}
  })(module);
  globalThis.__apAnswers = module.exports;

  // ---------------------------------------------------------------- electron/apply/dom.js (in-page scanner)
  ${scan}

  ${readList}

  globalThis.__apScan = __apScan;
  globalThis.__apReadListOptions = __apReadListOptions;
})();
`;
}

if (require.main === module) {
  const next = build();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (cur !== next) { console.error('extension/content/shared.js is stale — run: node extension/tools/sync-shared.js'); process.exit(1); }
    console.log('shared.js is up to date');
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${next.length} bytes)`);
  }
}

module.exports = { build, OUT };
