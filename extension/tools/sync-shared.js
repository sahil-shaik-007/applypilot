#!/usr/bin/env node
// Generates the extension files that are copies of shared app code, so the extension, the desktop auto-apply
// engine and the phone app always use the same field scanner, answerer and ATS rules:
//   content/shared.js        electron/apply/answers.js -> globalThis.__apAnswers (answerFromProfile, bestOption, ...)
//                            electron/apply/dom.js     -> globalThis.__apScan, globalThis.__apReadListOptions (in-page functions)
//   content/apply-engine.js  the phone app's auto-fill engine (web/mobile-autofill/build.mjs), as a plain script;
//                            injected into the job tab when the web app uses "Apply in browser"
//   lib/ats.js               web/client/src/native/ats.js -> globalThis.ApAts (detectAts, resolveApplyUrl, canAutoSubmit, siteOf, ...)
//
//   node extension/tools/sync-shared.js          write the files
//   node extension/tools/sync-shared.js --check  exit 1 if a committed file is stale
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { pathToFileURL } = require('url');

const ROOT = path.join(__dirname, '..', '..');
const EXT = path.join(__dirname, '..');
const OUT = path.join(EXT, 'content', 'shared.js');
const OUT_ENGINE = path.join(EXT, 'content', 'apply-engine.js');
const OUT_ATS = path.join(EXT, 'lib', 'ats.js');

function between(src, startMarker, endMarker) {
  const a = src.indexOf(startMarker);
  const b = src.indexOf(endMarker, a + 1);
  if (a < 0 || b < 0) throw new Error(`Marker not found: ${startMarker} / ${endMarker}`);
  return src.slice(a, b).trimEnd();
}

function build() {
  const answers = fs.readFileSync(path.join(ROOT, 'electron', 'apply', 'answers.js'), 'utf8').replace(/\r\n/g, '\n');
  const dom = fs.readFileSync(path.join(ROOT, 'electron', 'apply', 'dom.js'), 'utf8').replace(/\r\n/g, '\n');
  if (/\brequire\(/.test(answers)) throw new Error('answers.js now has require() calls — it can no longer be bundled verbatim');
  const scan = between(dom, 'function __apScan(cfg) {', '\nfunction __apReadListOptions(');
  const readList = between(dom, 'function __apReadListOptions(input) {', '\n/* eslint-enable no-undef */');
  return `// GENERATED by extension/tools/sync-shared.js from electron/apply/answers.js and electron/apply/dom.js.
// Do not edit by hand: change the desktop files and re-run \`node extension/tools/sync-shared.js\`.
/* eslint-disable */
(function () {
  if (globalThis.__apAnswers && globalThis.__apScan) return; // already injected into this frame
  const module = { exports: {} };
  // ---------------------------------------------------------------- electron/apply/answers.js
  (function (module) {
${answers}
  })(module);
  globalThis.__apAnswers = module.exports;

  // ---------------------------------------------------------------- electron/apply/dom.js (in-page scanner)
  ${scan}

  ${readList}

  globalThis.__apScan = __apScan;
  globalThis.__apReadListOptions = __apReadListOptions;
})();
`;
}

// The phone app's engine, built fresh from its sources by web/mobile-autofill/build.mjs (an ES module, hence the child process).
function buildEngine() {
  const code = 'import(process.argv[1]).then((m) => process.stdout.write(JSON.stringify(m.buildSource())))';
  const url = pathToFileURL(path.join(ROOT, 'web', 'mobile-autofill', 'build.mjs')).href;
  const { script } = JSON.parse(execFileSync(process.execPath, ['--input-type=module', '-e', code, url], { maxBuffer: 64 * 1024 * 1024 }).toString('utf8'));
  const nl = script.indexOf('\n');
  // Line 1 stays the engine's own header (the background reads the version from it).
  return `${script.slice(0, nl)}
// GENERATED by extension/tools/sync-shared.js from web/mobile-autofill/build.mjs (answers.js + dom.js + native/ats.js + runtime.js).
// Do not edit by hand: change the sources and re-run \`node extension/tools/sync-shared.js\`.
/* eslint-disable */
${script.slice(nl + 1)}`;
}

// native/ats.js is an ES module; the service worker loads it with importScripts(), so the exports become globalThis.ApAts.
function buildAts() {
  const src = fs.readFileSync(path.join(ROOT, 'web', 'client', 'src', 'native', 'ats.js'), 'utf8').replace(/\r\n/g, '\n');
  if (/^\s*import\s/m.test(src)) throw new Error('src/native/ats.js must not import anything');
  const names = [...src.matchAll(/^export\s+(?:const|function|let|class)\s+(\w+)/gm)].map((m) => m[1]);
  if (!names.length) throw new Error('src/native/ats.js has no exports');
  return `// GENERATED by extension/tools/sync-shared.js from web/client/src/native/ats.js.
// Do not edit by hand: change that file and re-run \`node extension/tools/sync-shared.js\`.
/* eslint-disable */
(function () {
${src.replace(/^export\s+(const|function|let|class)\s/gm, '$1 ').trimEnd()}

  globalThis.ApAts = { ${names.join(', ')} };
})();
`;
}

const TARGETS = [
  { out: OUT, build },
  { out: OUT_ENGINE, build: buildEngine },
  { out: OUT_ATS, build: buildAts },
];

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const t of TARGETS) {
    const next = t.build();
    const rel = path.relative(ROOT, t.out).replace(/\\/g, '/');
    if (check) {
      const cur = fs.existsSync(t.out) ? fs.readFileSync(t.out, 'utf8').replace(/\r\n/g, '\n') : '';
      if (cur !== next) { console.error(`${rel} is stale — run: node extension/tools/sync-shared.js`); stale++; }
    } else {
      fs.writeFileSync(t.out, next);
      console.log(`wrote ${rel} (${next.length} bytes)`);
    }
  }
  if (check) { if (stale) process.exit(1); console.log('shared.js, apply-engine.js and ats.js are up to date'); }
}

module.exports = { build, buildEngine, buildAts, TARGETS, OUT };
