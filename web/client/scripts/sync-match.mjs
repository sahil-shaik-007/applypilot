// Regenerates the ESM ports in web/shared/ from the desktop's CommonJS modules so the logic that runs
// on the phone is identical to the desktop app:
//   electron/eligibility.js    -> web/shared/eligibility.js     (whole module)
//   electron/match.js          -> web/shared/match.js           (whole module)
//   electron/tailoredResume.js -> web/shared/tailoredResume.js  (pure parts: truthfulness verifier, text/HTML render)
//   electron/csvImport.js      -> web/shared/csvImport.js       (pure parts: CSV parser, LinkedIn + tracker import)
// Modules with Node/Electron-only parts are ported with `pick`: only the named top-level declarations
// (plus the comments directly above them) are copied, and the result must be free of require()/Node globals.
// Run: node web/client/scripts/sync-match.mjs   (add --check to fail if a generated file is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ELECTRON = path.resolve(here, '../../../electron');
const SHARED = path.resolve(here, '../../shared');
const CHECK = process.argv.includes('--check');

const MODULES = [
  { name: 'eligibility.js' },
  { name: 'match.js' },
  { name: 'tailoredResume.js', pick: ['norm', 'verifyTruthful', 'esc', 'renderHtml', 'docToText'] },
  { name: 'resume.js', pick: ['experienceSection', 'MONTHS', 'IN_STATES', 'guessLabelled', 'DEGREES', 'BRANCHES', 'guessEducation', 'guessProfile'] },
  { name: 'csvImport.js', pick: ['parseCsv', 'toRecords', 'parseLinkedInConnections', 'SUFFIX', 'normCompany', 'sameCompany', 'COLS', 'detectColumns', 'mapStatus', 'parseTrackerCsv'] },
];
const PORTED = new Set(MODULES.map((m) => m.name));

const stripComments = (s) => s.replace(/\/\/.*$/gm, '');

/** Splits a CommonJS file into top-level declarations (column-0 `function`/`const`/`let`/`class`). */
function topLevel(src) {
  const lines = src.split('\n');
  const starts = [];
  const DECL = /^(?:async\s+)?(?:function\s*\*?\s*(\w+)|(?:const|let|var|class)\s+(\w+))/;
  lines.forEach((l, i) => { const m = l.match(DECL); if (m) starts.push({ i, name: m[1] || m[2] }); });
  const endAll = lines.findIndex((l) => /^module\.exports\s*=/.test(l));
  return starts.map((s, k) => {
    let from = s.i;
    while (from > 0 && /^\s*(\/\/|\/\*|\*)/.test(lines[from - 1])) from--; // attach the comment block above
    let to = k + 1 < starts.length ? starts[k + 1].i : (endAll >= 0 ? endAll : lines.length);
    // don't swallow the next declaration's leading comments
    while (to - 1 > s.i && /^\s*(\/\/|\/\*|\*)/.test(lines[to - 1])) to--;
    return { name: s.name, text: lines.slice(from, to).join('\n').replace(/\s+$/, '') };
  });
}

function convertRequires(body, name) {
  // const { a, b } = require('./mod');  ->  import { a, b } from './mod.js';
  return body.replace(/^const\s*\{([^}]*)\}\s*=\s*require\(\s*'\.\/([\w-]+)(?:\.js)?'\s*\);?\s*$/gm, (_, names, mod) => {
    if (!PORTED.has(`${mod}.js`)) throw new Error(`electron/${name} requires ./${mod}, which is not ported`);
    return `import { ${names.split(',').map((s) => s.trim()).filter(Boolean).join(', ')} } from './${mod}.js';`;
  });
}

function port({ name, pick }) {
  const src = fs.readFileSync(path.join(ELECTRON, name), 'utf8').replace(/\r\n/g, '\n');
  const exp = src.match(/^module\.exports\s*=\s*\{([^}]*)\};?\s*$/m);
  if (!exp) throw new Error(`electron/${name}: could not find the module.exports line`);
  const exported = exp[1].split(',').map((s) => s.trim()).filter(Boolean);
  let body;
  let exports;
  if (!pick) {
    body = convertRequires(src.replace(exp[0], `export { ${exported.join(', ')} };\n`), name);
    exports = exported;
  } else {
    const decls = topLevel(src);
    const missing = pick.filter((p) => !decls.some((d) => d.name === p));
    if (missing.length) throw new Error(`electron/${name}: declarations not found: ${missing.join(', ')}`);
    // Keep relative imports of ported modules the picked code relies on.
    const imports = [...src.matchAll(/^const\s*\{([^}]*)\}\s*=\s*require\(\s*'\.\/([\w-]+)(?:\.js)?'\s*\);?\s*$/gm)].map((m) => m[0]);
    const picked = decls.filter((d) => pick.includes(d.name)).map((d) => d.text);
    exports = exported.filter((e) => pick.includes(e));
    body = `${convertRequires(imports.join('\n'), name)}\n\n${picked.join('\n\n')}\n\nexport { ${exports.join(', ')} };\n`;
  }
  const code = stripComments(body);
  if (/\brequire\s*\(/.test(code)) throw new Error(`electron/${name} has a require() this script can't convert; add it to "pick" exclusions or port by hand`);
  if (/\b(process\.(env|argv|platform)|Buffer\.|__dirname|__filename)/.test(code)) throw new Error(`electron/${name} uses Node-only globals; narrow "pick"`);
  const header = `// ESM port of electron/${name} for the web PWA / phone apps (runs on the device, never on the server).\n`
    + `// GENERATED by web/client/scripts/sync-match.mjs${pick ? ' (pure parts only)' : ''}: do not edit by hand; edit the electron/ file and re-run.\n\n`;
  const out = header + body.replace(/^\n+/, '');
  const dest = path.join(SHARED, name);
  if (CHECK) {
    const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== out) throw new Error(`web/shared/${name} is stale: run node web/client/scripts/sync-match.mjs`);
    return exports.join(', ');
  }
  fs.writeFileSync(dest, out);
  return exports.join(', ');
}

for (const m of MODULES) console.log(`web/shared/${m.name} ${CHECK ? 'up to date' : 'regenerated'} (exports: ${port(m)})`);
