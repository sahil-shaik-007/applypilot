// Regenerates the ESM ports in web/shared/ from the desktop's CommonJS scoring modules so on-device
// scoring in the PWA is identical to the desktop app:
//   electron/eligibility.js -> web/shared/eligibility.js
//   electron/match.js       -> web/shared/match.js
// Run: node web/client/scripts/sync-match.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ELECTRON = path.resolve(here, '../../../electron');
const SHARED = path.resolve(here, '../../shared');
const FILES = ['eligibility.js', 'match.js'];

function port(name) {
  const src = fs.readFileSync(path.join(ELECTRON, name), 'utf8');
  const exp = src.match(/^module\.exports\s*=\s*\{([^}]*)\};?\s*$/m);
  if (!exp) throw new Error(`electron/${name}: could not find the module.exports line`);
  let body = src.replace(exp[0], `export { ${exp[1].split(',').map((s) => s.trim()).filter(Boolean).join(', ')} };\n`);
  // const { a, b } = require('./mod');  ->  import { a, b } from './mod.js';
  body = body.replace(/^const\s*\{([^}]*)\}\s*=\s*require\(\s*'\.\/([\w-]+)(?:\.js)?'\s*\);?\s*$/gm, (_, names, mod) => {
    if (!FILES.includes(`${mod}.js`)) throw new Error(`electron/${name} requires ./${mod}, which is not ported`);
    return `import { ${names.split(',').map((s) => s.trim()).filter(Boolean).join(', ')} } from './${mod}.js';`;
  });
  if (/\brequire\s*\(/.test(body.replace(/\/\/.*$/gm, ''))) throw new Error(`electron/${name} has a require() this script can't convert; port it by hand`);
  if (/\b(process\.(env|argv|platform)|Buffer\.|__dirname|__filename)/.test(body.replace(/\/\/.*$/gm, ''))) throw new Error(`electron/${name} uses Node-only globals; port it by hand`);
  const header = `// ESM port of electron/${name} for the web PWA (runs on the device, never on the server).\n`
    + '// GENERATED by web/client/scripts/sync-match.mjs: do not edit by hand; edit the electron/ file and re-run.\n\n';
  fs.writeFileSync(path.join(SHARED, name), header + body);
  return exp[1].trim();
}

for (const f of FILES) console.log(`web/shared/${f} regenerated (exports: ${port(f)})`);
