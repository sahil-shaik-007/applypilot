// Builds the injectable in-page auto-fill engine:
//   web/client/src/native/autofill.bundle.js   (ESM: export const AUTOFILL_SOURCE = "<script>", AUTOFILL_VERSION)
//   web/mobile-autofill/dist/autofill.js        (the raw script, handy for debugging / Safari Web Inspector)
//
// Plain concatenation (no bundler needed) into one IIFE:
//   1. electron/apply/answers.js            wrapped as a CommonJS module -> __answers
//   2. __apScan + __apReadListOptions       extracted verbatim from electron/apply/dom.js
//   3. web/client/src/native/ats.js         with `export` stripped
//   4. web/mobile-autofill/src/runtime.js
// The desktop files are the single source of truth: re-run this after changing them.
//
//   node web/mobile-autofill/build.mjs           (build)
//   node web/mobile-autofill/build.mjs --check   (fail if the committed bundle is stale)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '../..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const OUT_MODULE = path.join(ROOT, 'web/client/src/native/autofill.bundle.js');
const OUT_RAW = path.join(here, 'dist/autofill.js');

function answersModule() {
  const src = read('electron/apply/answers.js');
  if (/\brequire\s*\(/.test(src.replace(/\/\/.*$/gm, ''))) throw new Error('electron/apply/answers.js now has a require(); update build.mjs');
  return `const __answers = (function () {\n  const module = { exports: {} }; const exports = module.exports;\n${src}\n  return module.exports;\n})();\n`;
}

function scanFunctions() {
  const src = read('electron/apply/dom.js');
  const a = src.indexOf('function __apScan(');
  const b = src.indexOf('/* eslint-enable no-undef */', a);
  if (a < 0 || b < 0) throw new Error('electron/apply/dom.js: could not find __apScan ... eslint-enable markers');
  const body = src.slice(a, b);
  if (!/function __apReadListOptions\(/.test(body)) throw new Error('electron/apply/dom.js: __apReadListOptions moved');
  return body;
}

function atsModule() {
  const src = read('web/client/src/native/ats.js');
  if (/^\s*import\s/m.test(src)) throw new Error('src/native/ats.js must not import anything');
  return src.replace(/^export\s+(const|function|let|class)\s/gm, '$1 ');
}

export function buildSource() {
  const runtime = read('web/mobile-autofill/src/runtime.js');
  const body = [
    '// ---- electron/apply/answers.js', answersModule(),
    '// ---- electron/apply/dom.js (__apScan, __apReadListOptions)', scanFunctions(),
    '// ---- web/client/src/native/ats.js', atsModule(),
    '// ---- web/mobile-autofill/src/runtime.js', runtime,
  ].join('\n');
  const version = `1.0.0+${crypto.createHash('sha256').update(body).digest('hex').slice(0, 12)}`;
  const script = `/* ApplyPilot auto-fill engine ${version}. Generated by web/mobile-autofill/build.mjs */\n(function () {\n'use strict';\n${body.replace(/__AP_AUTOFILL_VERSION__/g, version)}\n})();\n`;
  new vm.Script(script, { filename: 'autofill.js' }); // syntax check
  return { script, version };
}

function moduleText({ script, version }) {
  return '// GENERATED by web/mobile-autofill/build.mjs. Do not edit: change electron/apply/{answers,dom}.js,\n'
    + '// web/client/src/native/ats.js or web/mobile-autofill/src/runtime.js and re-run `node web/mobile-autofill/build.mjs`.\n'
    + `export const AUTOFILL_VERSION = ${JSON.stringify(version)};\n`
    + `export const AUTOFILL_SOURCE = ${JSON.stringify(script)};\n`
    + 'export default AUTOFILL_SOURCE;\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const built = buildSource();
  const text = moduleText(built);
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT_MODULE) ? fs.readFileSync(OUT_MODULE, 'utf8') : '';
    if (cur !== text) { console.error('autofill.bundle.js is stale: run node web/mobile-autofill/build.mjs'); process.exit(1); }
    console.log(`autofill bundle up to date (${built.version})`);
  } else {
    fs.mkdirSync(path.dirname(OUT_RAW), { recursive: true });
    fs.writeFileSync(OUT_RAW, built.script);
    fs.writeFileSync(OUT_MODULE, text);
    console.log(`built ${path.relative(ROOT, OUT_MODULE)} (${built.version}, ${(built.script.length / 1024).toFixed(1)} KB)`);
  }
}
